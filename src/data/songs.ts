export function filterByCategory(key: string): Song[] {
  switch (key) {
    case 'best':
      return songs.filter((s) => s.tags.includes('精选'))
    case 'acoustic':
      return songs.filter((s) => s.tags.includes('弹唱友好'))
    case 'live':
      return songs.filter((s) => s.tags.includes('现场'))
    case 'early':
      return songs.filter((s) => s.year <= 2006)
    case 'city':
      return songs.filter((s) => !!s.city)
    case 'deep':
      return songs.filter((s) => s.tags.includes('冷门'))
    default:
      return songs
  }
}

/** 热门榜 */
export const topSongs = (n = 10) =>
  [...songs].sort((a, b) => b.playCount - a.playCount).slice(0, n)
